    if run_certification:
        env = dict(os.environ)
        env['PYTHONUTF8'] = '1'
        env['PYTHONIOENCODING'] = 'utf-8'
        with open(script_path, 'w', encoding='utf-8') as f:
            f.write(text.replace('@@CERT@@', 'certification pending'))
        try:
            proc = subprocess.run(
                [sys.executable, script_path], cwd=out_dir, env=env,
                capture_output=True, text=True, encoding='utf-8',
                errors='replace', timeout=_SUB_TIMEOUT_S)
        except subprocess.TimeoutExpired:
            run_err = 'self-run timed out (%ds)' % _SUB_TIMEOUT_S
            proc = None
        if proc is not None and proc.returncode != 0:
            run_err = (proc.stderr or '').strip()[-1500:]
        rep_path = os.path.join(out_dir, 'replay_%s_result.json' % mode)
        if run_err is None:
            with open(rep_path, encoding='utf-8') as f:
                rep = json.load(f)
            # tier2：params/perr 逐位一致计数 + ULP 容差（1e-12 相对）越界名单
            # （两段独立计数：exact/n_all 按 params 与 perr 分别统计，证书只报总和）
            exact, n_all, max_rel, bad_p, bad_e = {}, {}, 0.0, [], []
            for k, badlist in (('params', bad_p), ('perr', bad_e)):
                exact[k] = n_all[k] = 0
                for n in src[k]:
                    n_all[k] += 1
                    a, b = src[k][n], rep[k].get(n)
                    if b == a:
                        exact[k] += 1
                        continue
                    rel = abs(a - b) / max(abs(a), 1e-300) if b is not None else float('inf')
                    max_rel = max(max_rel, rel)
                    if rel > _REL_TOL:
                        badlist.append(n)
            checks['params'] = {'n': n_all['params'], 'exact': exact['params'],
                                'mismatch': bad_p, 'tol': _REL_TOL}
            checks['perr'] = {'n': n_all['perr'], 'exact': exact['perr'],
                              'mismatch': bad_e, 'tol': _REL_TOL}
            checks['max_rel_diff'] = max_rel
            checks['chi2_dof'] = rep['chi2_dof'] == src['chi2_dof']
            checks['dof'] = rep['dof'] == src['dof']
            checks['at_bound'] = sorted(rep.get('at_bound') or []) == \
                sorted(src.get('at_bound') or [])
            checks['n_points'] = rep['n_points'] == prov.get('n_points')
            cert_flag = all([not bad_p, not bad_e, checks['chi2_dof'],
                             checks['dof'], checks['at_bound'], checks['n_points']])
            if cert_flag:
                cert = (_CERT_OK
                        .replace('@@TS2@@', ts)
                        .replace('@@EXACT_N@@', str(exact['params'] + exact['perr']))
                        .replace('@@N_ALL@@', str(n_all['params'] + n_all['perr']))
                        .replace('@@MAX_REL@@', '%.2g' % max_rel)
                        .replace('@@REL_TOL@@', '%.0e' % _REL_TOL))
            else:
                det = []
                if bad_p:
                    det.append('#   params beyond tolerance: %s' % ', '.join(bad_p))
                if bad_e:
                    det.append('#   perr beyond tolerance: %s' % ', '.join(bad_e))
                for k in ('chi2_dof', 'dof', 'at_bound', 'n_points'):
                    if not checks[k]:
                        det.append('#   %s mismatch' % k)
                cert = _CERT_NO.replace('@@TS2@@', ts).replace(
                    '@@CERT_DETAIL@@', '\n'.join(det) or '#   (see receipt)')
        else:
            cert_flag = False
            cert = (_CERT_NO.replace('@@TS2@@', ts)
                    .replace('@@CERT_DETAIL@@',
                             '#   self-run failed: %s' % (run_err or 'unknown')))
        # 回填证书注释后重写（行为与实跑版本逐位一致，仅注释差异）
        text = text.replace('@@CERT@@', cert)
        compile(text, script_path, 'exec')
        with open(script_path, 'w', encoding='utf-8') as f:
            f.write(text)
    else:
        text = text.replace('@@CERT@@', 'certification skipped (run_certification=False)')
        with open(script_path, 'w', encoding='utf-8') as f:
            f.write(text)

    stems = ['replay_%s_result.json' % mode, 'replay_%s_curves.csv' % mode,
             'replay_%s_fit.png' % mode]
    produced = [os.path.join(out_dir, s) for s in stems]
    return {'script': script_path, 'out_dir': out_dir,
            'certified': cert_flag,
            'checks': checks if checks else None,
            'self_run_error': run_err,
            'replay_files_exist': {os.path.basename(p): os.path.isfile(p)
                                   for p in produced},
            'model_source_sha256': sha, 'calc_name': calc_name,
            'warnings': warns}


