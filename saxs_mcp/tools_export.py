def _calc_name(cfg, physics):
    """从 plugin 的 calc lambda 源码解析物理函数名（如 M.model_vec → 'model_vec'）。
    解析不到/闭包形态 → 显式报错（宁可报错不要猜错）。"""
    try:
        src = inspect.getsource(cfg['calc'])
    except (OSError, TypeError):
        raise ValueError("calc 适配函数源码不可得（闭包/C 形态），重放脚本暂不支持导出该模式")
    for cand in re.findall(r'\.([A-Za-z_]\w*)\s*\(', src):
        if callable(getattr(physics, cand, None)):
            return cand
    raise ValueError('calc 调用未解析到物理模块函数名（src=%r），暂不支持导出' % src)


def _import_scan(src_text):
    """entry 源码 import 白名单扫描，返回警告列表（不拒绝——自证对拍兜底）。"""
    warns = []
    for m in re.finditer(r'^\s*(?:import|from)\s+([.\w]+)', src_text, re.M):
        top = m.group(1).split('.')[0]
        if top not in _IMPORT_WHITELIST:
            warns.append('model 源码 import 白名单外模块 %r——脚本自包含性受限'
                         '（需随脚本环境安装该包）' % top)
    return sorted(set(warns))


def _q_unit_from_provenance(q_unit_input):
    """'A^-1 (x10 -> nm^-1)' → 'A^-1'；'nm^-1' → 'nm^-1'"""
    tok = (q_unit_input or '').split()[0]
    if tok not in ('A^-1', 'nm^-1'):
        raise ValueError('provenance.q_unit_input=%r 无法解析出 A^-1/nm^-1，拒绝导出'
                         % q_unit_input)
    return tok


