def init_p0_local(q, I):
    """Mirrors fitting.init_p0: B0 = mean of last 100 I; A0 = median((I-B0)/I_shape)."""
    B0 = float(I[-100:].mean())
    p0 = dict(INIT_DEFAULTS_M)
    p0.update(INIT_M)
    p0.update({k: float(v) for k, v in (FIXED or {}).items() if k in NAMES_M})
    p0.setdefault('A', 1.0)
    p0.setdefault('B', B0)
    w = q <= INIT_QMAX_M
    if not w.any():
        raise ValueError('init_qmax=%g does not intersect data q range (q_min=%.4g)'
                         % (INIT_QMAX_M, float(q.min())))
    p_shape = dict(p0)
    p_shape['A'] = 1.0
    p_shape['B'] = 0.0
    I0 = CALC(np.array([p_shape[n] for n in NAMES_M], dtype=float), q, FIXED)
    A0 = float(np.median((I[w] - B0) / I0[w]))
    if not np.isfinite(A0) or A0 <= 0.0:
        A0 = max(float(np.max(I[w])), 1e-12)
    p0['A'] = A0
    p0['B'] = B0
    return p0


def chi2_dof_local(res, npar):
    """Mirrors fitting.chi2_dof: perr = sqrt(diag(pinv(JtJ) * ssr/dof))."""
    dof = len(res.fun) - npar
    chi2 = float((res.fun ** 2).sum() / dof)
    pcov = np.linalg.pinv(res.jac.T @ res.jac) * (res.fun ** 2).sum() / dof
    perr = np.sqrt(np.diag(pcov))
    return chi2, dof, perr


def at_bound_local(x, lo, hi, names, rel=1e-3):
    """Mirrors fitting.at_bound (incl. the 5%-scale rule for wide double bounds)."""
    hits = []
    for v, l, h, n in zip(x, lo, hi, names):
        if np.isfinite(l) and np.isfinite(h):
            rng = h - l
            scale = max(abs(v), 1e-12)
            if rng > 1e3 * scale:
                if abs(v - l) <= 0.05 * scale or abs(h - v) <= 0.05 * scale:
                    hits.append(n)
            else:
                tol = rel * rng
                if abs(v - l) <= tol or abs(h - v) <= tol:
                    hits.append(n)
        else:
            tol = rel * max(abs(v), 1e-12)
            if (np.isfinite(l) and abs(v - l) <= tol) or (np.isfinite(h) and abs(h - v) <= tol):
                hits.append(n)
    return hits


def main():
    q, I, sig, summ = load_curve_local(DATA_FILE, Q_UNIT, QMIN, QMAX, FMT)
    print('data: n_used=%d  q=[%.6g, %.6g] nm^-1' % (len(q), summ['q_min'], summ['q_max']))

    p0 = init_p0_local(q, I)
    lo = np.array([BOUNDS_M[n][0] for n in NAMES_M], dtype=float)
    hi = np.array([BOUNDS_M[n][1] for n in NAMES_M], dtype=float)

    def resid(p):
        return (CALC(p, q, FIXED) - I) / sig

    res = least_squares(resid, np.array([p0[n] for n in NAMES_M], dtype=float),
                        bounds=(lo, hi), method='trf', x_scale='jac', max_nfev=20000)
    chi2, dof, perr = chi2_dof_local(res, N_FREE)
    at = at_bound_local(res.x, lo, hi, NAMES_M)

    p_dict = {n: float(v) for n, v in zip(NAMES_M, res.x)}
    perr_dict = {n: float(v) for n, v in zip(NAMES_M, perr)}

    print('fit: %d free params, chi2/dof = %.17g (dof=%d)' % (N_FREE, chi2, dof))
    for n in NAMES_M:
        print('  %-8s %.10g +/- %.4g%s' % (n, p_dict[n], perr_dict[n],
                                           '   [AT BOUND]' if n in at else ''))

    out = {'schema': 'replay-script-v0', 'kind': MODE_NAME,
           'params': p_dict, 'perr': perr_dict, 'chi2_dof': chi2,
           'dof': int(dof), 'at_bound': at, 'n_points': int(len(q))}
    with open(os.path.join(HERE, STEM + '_result.json'), 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=2)

    Ifit = CALC(res.x, q, FIXED)
    rel = (Ifit - I) / I
