    ax2.set_ylabel('(fit-data)/data')
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, STEM + '_fit.png'), dpi=150)
    print('written: %s_result.json / _curves.csv / _fit.png (next to this script)' % STEM)
    return 0


