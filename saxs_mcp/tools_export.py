def export_script(result_json, out_dir=None, run_certification: bool = True):
    """从 result.json 生成自包含重放脚本（默认含生成时自证对拍）。返回回执 dict。

    result_json: 源 result.json 绝对路径（saxs_report 产物，schema heps-saxs/result-v0）
    out_dir:     脚本与产物输出目录（绝对路径；默认 = result_json 所在目录）
    run_certification: True = 子进程实跑脚本并与源 result.json 逐位对拍
    """
    result_json = _resolve(result_json)
    out_dir = _resolve(out_dir) if out_dir else os.path.dirname(result_json)
    with open(result_json, encoding='utf-8') as f:
        src = json.load(f)
    if src.get('schema') != 'heps-saxs/result-v0':
        raise ValueError('schema=%r 非 heps-saxs/result-v0，拒绝导出（宁可报错不要猜错）'
                         % src.get('schema'))
    model = src['model_version'].split()[0]
    mode = src['kind']
    prov = src['provenance']
    q_unit = _q_unit_from_provenance(prov.get('q_unit_input'))
    fixed = prov.get('fixed')

    info = model_loader.load_model(model)
    if mode not in info['modes']:
        raise ValueError('模型 %s 无模式 %r' % (model, mode))
    cfg = info['modes'][mode]
    physics = info['physics']
    if cfg.get('fixed_keys'):
        raise ValueError('模式声明固定参数 fixed_keys=%s，重放脚本导出暂不支持该形态'
                         % list(cfg['fixed_keys']))

    entry_path = getattr(physics, '__file__', None)
    if not entry_path or not os.path.isfile(entry_path):
        raise ValueError('物理模块无 __file__（疑似桥接模型），暂不支持导出')
    with open(entry_path, encoding='utf-8') as f:
        model_src = f.read()
    sha = hashlib.sha256(model_src.encode('utf-8')).hexdigest()
    warns = _import_scan(model_src)
    calc_name = _calc_name(cfg, physics)

    os.makedirs(out_dir, exist_ok=True)
    script_path = os.path.join(out_dir, 'replay_%s.py' % mode)
    ts = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')

    text = _TEMPLATE
    for tok, val in (
        ('@@TOOL_VER@@', _TOOL_VER),
        ('@@MODEL_VER@@', src['model_version']),
        ('@@TS@@', ts),
        ('@@RESULT_JSON@@', result_json),
        ('@@DATA_FILE_COMMENT@@', prov.get('data_file', '?')),
        ('@@MODEL_SHA256@@', sha),
        ('@@MODE@@', mode),
        ('@@DATA_FILE@@', repr(prov.get('data_file'))),
        ('@@Q_UNIT@@', repr(q_unit)),
        ('@@QMIN@@', repr(float(prov['qmin']))),
        ('@@QMAX@@', repr(float(prov['qmax']))),
        ('@@FMT@@', repr(prov.get('fmt'))),
        ('@@FIXED@@', repr(fixed)),
        ('@@MODE_R@@', repr(mode)),
        ('@@NAMES@@', repr(list(cfg['names']))),
        ('@@INIT@@', repr(dict(cfg['init']))),
        ('@@INIT_DEFAULTS@@', repr(dict(cfg.get('init_defaults') or {}))),
        ('@@INIT_QMAX@@', repr(float(cfg['init_qmax']))),
        ('@@BOUNDS@@', repr({k: (v[0], v[1]) for k, v in cfg['bounds'].items()})),
        ('@@CALC_NAME@@', calc_name),
        ('@@CALC_NAME_R@@', repr(calc_name)),
        ('@@MODEL_SRC@@', model_src.rstrip('\n')),
    ):
        text = text.replace(tok, val)

